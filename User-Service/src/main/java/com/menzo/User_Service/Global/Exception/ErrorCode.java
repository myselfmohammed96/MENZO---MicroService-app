package com.menzo.User_Service.Global.Exception;

import lombok.Getter;
import org.springframework.http.HttpStatus;

@Getter
public enum ErrorCode {
    VALIDATION_FAILED(HttpStatus.BAD_REQUEST),
    MALFORMED_REQUEST(HttpStatus.BAD_REQUEST),
    INVALID_PROFILE_PICTURE(HttpStatus.BAD_REQUEST),
    FILE_TOO_LARGE(HttpStatus.PAYLOAD_TOO_LARGE),
    UNSUPPORTED_MEDIA_TYPE(HttpStatus.UNSUPPORTED_MEDIA_TYPE),
    METHOD_NOT_ALLOWED(HttpStatus.METHOD_NOT_ALLOWED),
    RESOURCE_NOT_FOUND(HttpStatus.NOT_FOUND),

    EMAIL_ALREADY_REGISTERED(HttpStatus.CONFLICT),
    ACCOUNT_PENDING_VERIFICATION(HttpStatus.CONFLICT),
    USER_ALREADY_EXISTS(HttpStatus.CONFLICT),

    OTP_RATE_LIMITED(HttpStatus.TOO_MANY_REQUESTS),
    OTP_SEND_FAILED(HttpStatus.SERVICE_UNAVAILABLE),
    OTP_INVALID(HttpStatus.BAD_REQUEST),
    OTP_EXPIRED(HttpStatus.BAD_REQUEST),
    OTP_NOT_FOUND(HttpStatus.BAD_REQUEST),
    OTP_VERIFY_LIMIT_EXCEEDED(HttpStatus.TOO_MANY_REQUESTS),
    OTP_VERIFY_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),
    USER_NOT_FOUND(HttpStatus.NOT_FOUND),
    ALREADY_VERIFIED(HttpStatus.CONFLICT),

    INVALID_CREDENTIALS(HttpStatus.UNAUTHORIZED),
    ACCOUNT_NOT_VERIFIED(HttpStatus.FORBIDDEN),
    ACCOUNT_DISABLED(HttpStatus.FORBIDDEN),
    ACCOUNT_USES_SOCIAL_LOGIN(HttpStatus.BAD_REQUEST),
    TOO_MANY_LOGIN_ATTEMPTS(HttpStatus.TOO_MANY_REQUESTS),
    GOOGLE_TOKEN_INVALID(HttpStatus.UNAUTHORIZED),
    GOOGLE_EMAIL_NOT_VERIFIED(HttpStatus.FORBIDDEN),
    AUTH_SERVICE_UNAVAILABLE(HttpStatus.SERVICE_UNAVAILABLE),

    FILE_STORAGE_FAILED(HttpStatus.INTERNAL_SERVER_ERROR),
    INTERNAL_ERROR(HttpStatus.INTERNAL_SERVER_ERROR);

    private final HttpStatus status;

    ErrorCode(HttpStatus status) {
        this.status = status;
    }
}
